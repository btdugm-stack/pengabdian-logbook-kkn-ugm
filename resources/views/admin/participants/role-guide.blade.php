  <h2>Arti Wilayah per Peran</h2>
  <dl class="detail-list">
    <div><dt>Mahasiswa</dt><dd>Lokasi penempatan, sebaiknya sampai sub-unit. Mengisi presensi dan logbook pribadi.</dd></div>
    <div><dt>Kormasit</dt><dd>Ketua sub-unit: tetap mengisi presensi dan logbook sendiri, bisa mengisi logbook kelompok, dan memantau sub-unitnya. Isi dengan sub-unit penempatannya.</dd></div>
    <div><dt>Korcam</dt><dd>Ketua kecamatan: sama seperti Kormasit, tetapi memantau seluruh kecamatan yang menaungi wilayahnya.</dd></div>
    <div><dt>DPL</dt><dd>Kosongkan wilayah. Mahasiswa bimbingannya diatur admin di menu Penugasan DPL, atau dipilih sendiri oleh DPL; hanya logbook mereka yang bisa direviu.</dd></div>
    <div><dt>Fakultas/Prodi</dt><dd>Kosongkan wilayah, isi kolom Fakultas. Hanya melihat mahasiswa dari fakultas itu.</dd></div>
    <div><dt>Pimpinan</dt><dd>Kosongkan. Hanya melihat angka agregat seluruh wilayah, tanpa data per mahasiswa.</dd></div>
    <div><dt>Admin LPPM</dt><dd>Kosongkan. Kelola akun dan master data, mereviu, serta input logbook atas nama mahasiswa.</dd></div>
    <div><dt>Super Admin</dt><dd>Kosongkan; punya semua hak Admin LPPM dan satu-satunya yang bisa memberi atau mengubah peran Super Admin.</dd></div>
  </dl>
  <p style="margin:16px 0 0">Ketua melihat semua mahasiswa di wilayahnya dan di bawahnya. DPL melihat mahasiswa yang ditugaskan kepadanya, di wilayah mana pun.</p>
